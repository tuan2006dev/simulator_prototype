import assert from 'node:assert/strict';
import {createIsland} from '../src/core/factory';
import {createCivilization} from '../src/core/civilization';
import {enableSettlement,tickCargo,openingMilestones} from '../src/core/settlement';
import {placeBuilding,assignWorker,tickBuildings,buildingSiteLock} from '../src/renderer/BuildingManager';
import {SimulationSession} from '../src/core/SimulationSession';
import {encodeSave,decodeSave} from '../src/core/SaveSystem';
import type {WorldMap} from '../src/renderer/WorldMap';
const map:WorldMap={width:20,height:12,tiles:Array.from({length:12},()=>Array(20).fill('grass')),landTiles:[]};
for(let y=0;y<12;y++)for(let x=0;x<20;x++)map.landTiles.push({x,y});
const island=createIsland('Khởi nguyên',5);island.civilization=createCivilization();enableSettlement(island);
island.dailyLife!.campfire={tileX:2,tileY:2,fuel:12,graceUntil:30,lit:true};
